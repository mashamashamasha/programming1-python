# 1. DEFINE the function
def organize_march(city):
    """Prints a mobilization message for the movement."""
    print(f"--- CITIZEN ALERT: {city.upper()} ---")
    print(f"Join us in {city}! We are expecting all of you, brothers and sisters. \nRequirement: Peace, discipline, and a heart for justice.")


# 2. CALL the function for different locations
organize_march("Birmingham")
organize_march("Montgomery")
organize_march("Washington")